/**
 * Turns the production build into ONE self-contained HTML file for sharing
 * (e.g. emailing a preview to the client). Run after `pnpm build`:
 *
 *   pnpm export:static   →  static-export/dr-panda-homepage.html
 *
 * CSS, fonts, images and the icon are inlined. The Next/React runtime is
 * removed and replaced by a small plain-JS script (src/static/enhance.ts).
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import sharp from "sharp";
import { build } from "rolldown";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const r = (...p) => path.join(root, ...p);
const dataUri = (buf, type) => `data:${type};base64,${buf.toString("base64")}`;

let html = await readFile(r(".next/server/app/index.html"), "utf8").catch(() => {
  throw new Error("No build found. Run `pnpm build` first.");
});

// 1. Drop the React/Next runtime: external chunks, flight data, preloads.
html = html
  .replace(/<script[^>]*\bsrc="[^"]*"[^>]*><\/script>/g, "")
  .replace(/<script(?: id="[^"]*")?>(?:\(self\.__next_f|self\.__next_f|\(globalThis\["TURBOPACK"\])[\s\S]*?<\/script>/g, "")
  .replace(/<link rel="(?:preload|modulepreload)"[^>]*>/g, "")
  .replace(/<link rel="canonical"[^>]*>/g, "");

// 2. Inline the stylesheet, with fonts as data URIs.
const cssLinks = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)"[^>]*>/g)];
for (const [tag, href] of cssLinks) {
  const cssPath = r(".next", href.replace(/^\/_next\//, ""));
  let css = await readFile(cssPath, "utf8");
  const fonts = [...new Set([...css.matchAll(/url\((\.\.\/media\/[^)]+\.woff2)\)/g)].map((m) => m[1]))];
  for (const f of fonts) {
    const buf = await readFile(path.resolve(path.dirname(cssPath), f));
    css = css.replaceAll(`url(${f})`, `url(${dataUri(buf, "font/woff2")})`);
  }
  html = html.replace(tag, `<style>${css}</style>`);
}

// 3. Images: every /_next/image?url=… becomes one embedded WebP (max 1200px wide).
const images = {};
async function embed(publicPath) {
  if (!images[publicPath]) {
    const buf = await sharp(r("public", publicPath))
      .resize({ width: 1200, withoutEnlargement: true })
      .webp({ quality: 78 })
      .toBuffer();
    images[publicPath] = dataUri(buf, "image/webp");
  }
  return images[publicPath];
}
html = html.replace(/\s(?:srcSet|sizes)="[^"]*"/g, "");
for (const m of [...html.matchAll(/src="\/_next\/image\?url=([^&"]+)[^"]*"/g)]) {
  html = html.replace(m[0], `src="${await embed(decodeURIComponent(m[1]))}"`);
}
// Concern images the switcher swaps in later.
const siteSrc = await readFile(r("src/content/site.ts"), "utf8");
for (const [, p] of siteSrc.matchAll(/image:\s*"([^"]+)"/g)) await embed(p);

// 4. Favicon and home-screen icon (generated by scripts/make-logo.mjs).
const icon = dataUri(await readFile(r("src/app/icon.png")), "image/png");
const appleIcon = dataUri(await readFile(r("src/app/apple-icon.png")), "image/png");
html = html
  .replace(/(<link rel="icon" href=")[^"]*"/, `$1${icon}"`)
  .replace(/(<link rel="apple-touch-icon" href=")[^"]*"/, `$1${appleIcon}"`);
// The header logo is a plain <img>, not next/image.
for (const m of [...html.matchAll(/src="(\/images\/[^"]+\.(png|svg))"/g)]) {
  const type = m[2] === "svg" ? "image/svg+xml" : "image/png";
  html = html.replace(m[0], `src="${dataUri(await readFile(r("public", m[1])), type)}"`);
}

// 5. Plain-JS behaviour, bundled from TypeScript.
const out = await build({
  input: r("src/static/enhance.ts"),
  resolve: { alias: { "@": r("src") } },
  write: false,
  output: { format: "iife", minify: true },
});
const js = out.output[0].code.replace(/<\/script/gi, "<\\/script");
html = html.replace(
  "</body>",
  `<script>window.__STATIC_IMAGES=${JSON.stringify(images)}</script><script>${js}</script></body>`,
);

if (/\/_next\//.test(html)) {
  const left = [...new Set(html.match(/\/_next\/[^"' )]+/g))];
  throw new Error(`Unresolved build paths left in the export:\n${left.join("\n")}`);
}

await mkdir(r("static-export"), { recursive: true });
const file = r("static-export/dr-panda-homepage.html");
await writeFile(file, html);
console.log(`Wrote ${path.relative(root, file)} (${(Buffer.byteLength(html) / 1024).toFixed(0)} KB)`);
